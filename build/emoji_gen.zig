//! Build-time tool: turns gemoji's emoji.json plus GitHub's custom emoji names into a sorted Zig table.
//! Usage: emoji_gen <emoji.json> <custom-emoji.txt> <out.zig>

const std = @import("std");

const Gemoji = struct {
    emoji: []const u8,
    aliases: []const []const u8,
};

const Entry = struct {
    name: []const u8,
    /// The Unicode sequence, or null for GitHub's image-only custom emoji.
    value: ?[]const u8,

    fn lessThan(_: void, a: Entry, b: Entry) bool {
        return std.mem.lessThan(u8, a.name, b.name);
    }
};

pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 4) return error.Usage;

    const cwd = std.Io.Dir.cwd();
    const json = try cwd.readFileAlloc(io, args[1], arena, .limited(16 << 20));
    const custom = try cwd.readFileAlloc(io, args[2], arena, .limited(1 << 20));
    const parsed = try std.json.parseFromSlice([]const Gemoji, arena, json, .{ .ignore_unknown_fields = true });

    var entries: std.ArrayList(Entry) = .empty;
    for (parsed.value) |g| {
        for (g.aliases) |alias| try entries.append(arena, .{ .name = alias, .value = g.emoji });
    }
    var lines = std.mem.tokenizeAny(u8, custom, "\r\n");
    while (lines.next()) |name| try entries.append(arena, .{ .name = name, .value = null });
    std.mem.sort(Entry, entries.items, {}, Entry.lessThan);

    var out: std.Io.Writer.Allocating = .init(arena);
    const w = &out.writer;
    try w.writeAll("//! Generated by build/emoji_gen.zig.\n\npub const Entry = struct { name: []const u8, value: ?[]const u8 };\n\npub const entries = [_]Entry{\n");
    for (entries.items) |e| {
        if (e.value) |v| {
            try w.print("    .{{ .name = \"{f}\", .value = \"{f}\" }},\n", .{ std.zig.fmtString(e.name), std.zig.fmtString(v) });
        } else {
            try w.print("    .{{ .name = \"{f}\", .value = null }},\n", .{std.zig.fmtString(e.name)});
        }
    }
    try w.writeAll("};\n");
    try cwd.writeFile(io, .{ .sub_path = args[3], .data = out.written() });
}
